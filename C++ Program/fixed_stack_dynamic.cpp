#include <bits/stdc++.h>
using namespace std;

// Fixed Stack Dynamic: Size is fixed at compile time
int main() {
    int arr[5] = {10, 20, 30, 40, 50};
    cout << "Fixed Stack Dynamic Array Elements: ";
    for(int i = 0; i < 5; i++) {
        cout << arr[i] << " ";
    }
    cout << endl;
    return 0;
}